
import 'dart:async';

/// A service class to demonstrate asynchronous data fetching and stream generation.
/// 
/// Regarding your question: What is 'yield'?
/// In Dart, 'yield' is a keyword used in generator functions (functions marked 
/// with 'async*' or 'sync*'). It provides a value to the stream or iterable 
/// being generated without terminating the function. 
/// 
/// Think of 'yield' as a "pause and emit" operation: 
/// 1. The function reaches the 'yield' line.
/// 2. It emits the value to the consumer (the listener of the stream).
/// 3. The function execution pauses at that point until the consumer requests 
///    the next value.
/// 4. The function resumes from exactly where it left off.
class DataService {
  /// Fetches a single string value after a delay.
  Future<String> fetchData() async {
    await Future.delayed(const Duration(seconds: 2));
    return 'Fetched Data';
  }

  /// Provides a stream of data updates.
  /// 
  /// The 'async*' modifier tells Dart this function returns a Stream.
  /// Inside the loop, 'yield i' sends the current iteration value 
  /// into the stream pipeline.
  Stream<int> getDataStream() async* {
    for (int i = 1; i <= 5; i++) {
      await Future.delayed(const Duration(milliseconds: 500));
      yield i; // Emit value 'i' to the stream
    }
  }
}

Future<void> main() async {
  final service = DataService();

  print('--- Starting Async Tasks ---');

  // Handling the future
  print('Fetching data...');
  final futureResult = await service.fetchData();
  print('Data fetched: $futureResult');

  // Handling the stream
  print('Starting stream (will emit 5 values)...');
  
  try {
    // The 'await for' loop automatically handles the subscription 
    // to the Stream generated by 'yield' statements.
    await for (final value in service.getDataStream()) {
      print('Stream event (emitted via yield): $value');
    }
    print('Stream completed successfully.');
  } catch (e, stackTrace) {
    print('An error occurred in the stream: $e');
    print(stackTrace);
  }

  print('--- All tasks complete ---');
}
